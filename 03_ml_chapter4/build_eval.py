def _run(p,text,bold=False,italic=False,color=None,size=12):
    r=p.add_run(text);r.bold=bold;r.italic=italic;r.font.size=Pt(size);r.font.name="Times New Roman"
    if color: r.font.color.rgb=color
    return r
def P(content="",bold=False,italic=False,color=None,align="just",size=12,after=6,before=0):
    p=d.add_paragraph();p.alignment={"just":WD_ALIGN_PARAGRAPH.JUSTIFY,"c":WD_ALIGN_PARAGRAPH.CENTER,"l":WD_ALIGN_PARAGRAPH.LEFT}[align]
    p.paragraph_format.space_after=Pt(after);p.paragraph_format.space_before=Pt(before);p.paragraph_format.line_spacing=1.5
    if isinstance(content,list):
        for t,b in content: _run(p,t,bold=b,size=size,color=color)
    elif content:
        _run(p,content,bold=bold,italic=italic,color=color,size=size)
    return p
def H(text,size=14,color=NAVY,before=12):
    p=P(align="l",after=5,before=before);_run(p,text,bold=True,size=size,color=color);return p
def bullet(content):
    p=d.add_paragraph(style="List Bullet");p.paragraph_format.line_spacing=1.5;p.paragraph_format.space_after=Pt(3)
    if isinstance(content,str): content=[(content,False)]
    for t,b in content: _run(p,t,bold=b)
    return p
def table(headers,rows):
    t=d.add_table(rows=1,cols=len(headers));t.alignment=WD_TABLE_ALIGNMENT.CENTER;t.style="Table Grid"
    for j,h in enumerate(headers):
        c=t.rows[0].cells[j];c.text="";r=c.paragraphs[0].add_run(h);r.bold=True;r.font.size=Pt(10);r.font.color.rgb=RGBColor(0xff,0xff,0xff);r.font.name="Times New Roman"
        sh=OxmlElement("w:shd");sh.set(QN("w:fill"),"1f3a56");c._tc.get_or_add_tcPr().append(sh)
    for row in rows:
        cells=t.add_row().cells
        for j,v in enumerate(row):
            cells[j].text="";pp=cells[j].paragraphs[0];pp.paragraph_format.line_spacing=1.0
            r=pp.add_run(str(v));r.font.size=Pt(9);r.font.name="Times New Roman"
    return t

